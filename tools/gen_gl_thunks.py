#!/usr/bin/env python3
"""Generate runtime/gl/gl_thunks.c: one host function per OpenGL command, called by the game through the pointers
eglGetProcAddress hands out (runtime/gl/egl.c).

Each thunk reads the arguments the way the game's AArch64 code passes them (AAPCS64: integers and pointers in x0-x7,
float/double in v0-v7, the rest in 8-byte stack slots in argument order), calls the host driver's function, and puts
the result in x0 or v0. Guest pointers are host pointers (runtime/rt.h), so buffers pass through unchanged.

Commands with callback parameters (GLDEBUGPROC...) can't take a guest function pointer: they get a logging stub.

Usage: gen_gl_thunks.py <out.c> [gl.xml]   (gl.xml: from the glad2 package unless given)
"""
import os
import sys
import xml.etree.ElementTree as ET

FLOAT = {'GLfloat', 'GLclampf'}
DOUBLE = {'GLdouble', 'GLclampd'}
CALLBACK = {'GLDEBUGPROC', 'GLDEBUGPROCARB', 'GLDEBUGPROCKHR', 'GLDEBUGPROCAMD', 'GLVULKANPROCNV'}
INT64 = {'GLint64', 'GLuint64', 'GLint64EXT', 'GLuint64EXT', 'GLsizeiptr', 'GLintptr', 'GLsizeiptrARB',
         'GLintptrARB', 'GLsync', 'GLeglImageOES', 'GLeglClientBufferEXT', 'GLvdpauSurfaceNV'}


def find_xml():
    import glad
    return os.path.join(os.path.dirname(glad.__file__), 'files', 'gl.xml')


def text_of(e):
    return ''.join(e.itertext()).strip()


def parse(path):
    root = ET.parse(path).getroot()
    cmds = {}
    for c in root.find('commands').findall('command'):
        proto = c.find('proto')
        name = proto.find('name').text
        ptype = proto.find('ptype')
        full = text_of(proto)
        ret = full[:full.rfind(name)].strip()
        params = []
        for p in c.findall('param'):
            pname = p.find('name').text
            pt = p.find('ptype')
            decl = text_of(p)
            ctype = decl[:decl.rfind(pname)].strip()
            params.append((ctype, pt.text if pt is not None else None, pname))
        cmds[name] = (ret, ptype.text if ptype is not None else None, params)
    return cmds


def kind(ctype, base):
    if '*' in ctype or '[' in ctype:
        return 'ptr'
    if base in CALLBACK:
        return 'cb'
    if base in FLOAT:
        return 'f'
    if base in DOUBLE:
        return 'd'
    if base in INT64:
        return 'i64'
    return 'i'


def host_type(ctype):
    # keep the GL typedefs (from SDL's / the platform's GL headers)
    t = ctype.replace('const ', 'const ').strip()
    return t or 'void'


def emit(cmds, out):
    w = out.write
    w('// Generated by tools/gen_gl_thunks.py from the Khronos GL registry - do not edit.\n')
    w('#include "gl_host.h"\n\n')
    names = sorted(cmds)
    emitted = []
    for name in names:
        ret, rbase, params = cmds[name]
        kinds = [kind(ct, b) for ct, b, _ in params]
        fn = f'th_{name}'
        emitted.append(name)
        if 'cb' in kinds:
            w(f'static void {fn}(Cpu *c) {{ (void)c; gl_unsupported("{name}"); }}\n')
            continue
        args, xi, vi, si = [], 0, 0, 0
        for (ct, b, pn), k in zip(params, kinds):
            ht = host_type(ct)
            if k in ('f', 'd'):
                if vi < 8:
                    src = f'c->v[{vi}]'
                    vi += 1
                    args.append(f'gl_v{"f" if k == "f" else "d"}({src})')
                else:
                    args.append(f'gl_s{"f" if k == "f" else "d"}(c, {si})')
                    si += 1
            else:
                if xi < 8:
                    src = f'c->x[{xi}]'
                    xi += 1
                else:
                    src = f'gl_si(c, {si})'
                    si += 1
                args.append(f'({ht})(uintptr_t){src}' if k == 'ptr' or ht in ('GLsync', 'GLeglImageOES')
                            else f'({ht}){src}')
        proto = ', '.join(host_type(ct) for ct, _, _ in params) or 'void'
        rk = 'void' if ret == 'void' else kind(ret, rbase)
        call = f'f({", ".join(args)})'
        w(f'static void {fn}(Cpu *c) {{\n')
        w(f'    GL_TRACE("{name}", c);\n')
        w(f'    typedef {ret} (APIENTRY *F)({proto});\n')
        w(f'    static F f;\n')
        w(f'    if (!f && !(f = (F)gl_proc("{name}"))) {{ gl_missing("{name}"); c->x[0] = 0; return; }}\n')
        if not params:
            pass
        if rk == 'void':
            w(f'    {call};\n')
        elif rk == 'f':
            w(f'    gl_retf(c, {call});\n')
        elif rk == 'd':
            w(f'    gl_retd(c, {call});\n')
        elif rk == 'ptr' or ret in ('GLsync',):
            w(f'    c->x[0] = (uint64_t)(uintptr_t){call};\n')
        else:
            w(f'    c->x[0] = (uint64_t){call};\n')
        w('}\n')
    w('\nconst GlThunk gl_thunks[] = {\n')
    for name in emitted:
        w(f'    {{"{name}", th_{name}}},\n')
    w('};\n')
    w(f'const int gl_thunk_count = {len(emitted)};\n')


def main():
    out = sys.argv[1]
    xml = sys.argv[2] if len(sys.argv) > 2 else find_xml()
    cmds = parse(xml)
    with open(out, 'w', newline='\n') as f:
        emit(cmds, f)
    print(f'{len(cmds)} GL commands -> {out}')


if __name__ == '__main__':
    main()
